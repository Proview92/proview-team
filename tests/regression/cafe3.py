from playwright.sync_api import sync_playwright
def tryIn(pg,pid):
    pg.evaluate("document.querySelectorAll('#toast').forEach(t=>t.innerText='')")
    st=pg.evaluate("pid=>{doClock(pid,'in',{src:'clock'});return whoState(P(pid)).st}",pid); pg.wait_for_timeout(150)
    return st+' | '+str(pg.evaluate("document.querySelector('#toast')?.innerText"))
